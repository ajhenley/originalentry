"""Schema guard: every model agrees with the live database.

This exists because of a specific mistake. `section_staff`'s migration created
`ix_section_staff_user`, but the model did not declare it, so `db.metadata` did not know the index
existed. Nothing was visibly broken -- the index was there, the query used it -- but the next
`flask db migrate` would have autogenerated a migration *dropping* it, and the scoping query that
reads it on every request would have quietly fallen to a sequential scan.

It is deliberately repo-wide rather than scoped to the table that taught us this. A filtered
version only guards the one mistake already made; this one guards the shape of it. If you are here
because this test failed, the fix is almost always to make the model match the migration -- declare
the index, the constraint or the column the migration created. Narrowing the comparison to get
green would hand the next person the same silent dropped index.
"""

import pytest
from alembic.autogenerate import compare_metadata
from alembic.migration import MigrationContext
from originalentry.extensions import db

pytestmark = pytest.mark.db


def test_no_model_has_drifted_from_the_database(session):
    """``compare_metadata`` is what ``flask db migrate`` itself runs, so an empty diff is the
    statement that an autogenerate right now would produce an empty migration."""
    # The test's own connection: reflection is read-only, so this needs no second connection to
    # the database and stays inside the per-test transaction.
    # Alembic's comparison defaults: no compare_type or compare_server_default. This checks what
    # `flask db migrate` checks, so server-default drift is not covered.
    context = MigrationContext.configure(session.connection())
    drift = compare_metadata(context, db.metadata)

    assert drift == [], (
        "the models and the database disagree -- an autogenerate would emit these "
        f"{len(drift)} change(s), so make the models match the migrations:\n"
        + "\n".join(f"  {change}" for change in drift)
    )
